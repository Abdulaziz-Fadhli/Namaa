const cite = sec => (sec.startsWith('دليل') ? sec : `دليل الهيئة §${sec}`);

// السهم أو الصندوق بالاسم أو الرمز: من قاعدة الأوراق (src/securities) وأحكامها من §3.6 و§3.9
function securityAnswer(q, raw) {
  const ticker = raw.match(/\b([A-Za-z]{1,5})\b/)?.[1];
  const code = raw.match(/\b(\d{4})\b/)?.[1];
  // الكلمات الأصلية (بإملائها) بعد حذف كلمات السؤال، حتى يظهر اسم الصندوق كما كتبه المستخدم
  const words = raw.replace(/[؟?!.,،]/g, ' ').split(/\s+/)
    .filter(w => { const n = normalizeAr(w); return n && !STOP.has(n) && !/^\d+$/.test(n); })
    .map(w => w.replace(/^(ب|و)(?=ال)/, ''));
  const cand = code || (ticker && ticker.length >= 2 ? ticker : null) || words.join(' ');
  if (!cand) return null;
  const intent = /(مضارب|اضارب|متاجر|بيع سريع)/.test(q) ? 'TRADE' : 'INVEST';
  const r = check(cand, { intent });
  if (!r.found) return null;
  const name = `${r.name || r.nameEn}${r.symbol ? ` (${r.symbol})` : ''}`;
  return {
    text: `${name}: ${r.headline}. ${r.detail}`,
    cite: cite(r.type === 'COMPANY' ? '3.6' : '3.9'),
    act: ['ربط تطبيق تداول', '/app/assets/add/apps'],
  };
}

// يرجع { text, cite?, act?: [عنوان, مسار], miss? }
export function answer(question, ctx = {}) {
  const raw = String(question ?? '').trim();
  const q = normalizeAr(raw).replace(/[؟?!.,،]/g, ' ').replace(/\s+/g, ' ').trim();
  if (!q) return { text: 'اكتب سؤالك عن الزكاة، مثل: كم زكاتي؟ أو هل في الذهب زكاة؟', miss: true };
  for (const [ks, text] of NOT_COVERED) if (ks.some(k => q.includes(normalizeAr(k)))) return { text, miss: true };

  // سؤال عن سهم أو صندوق باسمه: قبل الأجوبة العامة
  const stockish = /(سهم|اسهم|شركه|صندوق|\b[A-Za-z]{2,5}\b|\b\d{4}\b)/.test(q) || /\b[A-Z]{2,5}\b/.test(raw);
  const named = q.split(' ').filter(w => !STOP.has(w)).length > 0;
  if (stockish && named) { const s = securityAnswer(q, raw); if (s) return s; }

  let best = null, score = 0;
  for (const e of KB) {
    let s = 0;
    for (const k of e.k) { const nk = normalizeAr(k); if (q.includes(nk)) s += 1 + nk.split(' ').length; }
    if (s > score) { best = e; score = s; }
  }
  if (best) return { text: best.a(ctx), cite: cite(best.sec), act: best.act };
  // اسم شركة أو صندوق وحده (مثل «أرامكو»)
  if (named) { const s = securityAnswer(q, raw); if (s) return s; }
  if (GREET.some(g => q.startsWith(normalizeAr(g)))) return { text: 'هلا! اسألني عن زكاتك: كم ومتى، أو حكم الذهب والأسهم والعقار والديون، وأجاوبك من دليل هيئة الزكاة مع رقم الفقرة.' };
  return { text: 'ما لقيت جواب هذا السؤال في دليل هيئة الزكاة لزكاة الأفراد، وما أجاوب من عندي. جرّب صياغة ثانية، أو ارجع فيه لأهل العلم.', miss: true };
}
