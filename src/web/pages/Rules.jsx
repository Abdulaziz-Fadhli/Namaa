export function Rules() {
  const g = ZATCA.guides.individual;
  return (
    <Card title="الأحكام ومصادرها" desc={`كل حكم يطبقه نماء، ورقم فقرته في ${g.title} (${g.edition})`}>
      {RULES.map(([group, list]) => (
        <section key={group} style={{ marginTop: 18 }}>
          <h3 className="t13 b7 sub" style={{ marginBottom: 4 }}>{group}</h3>
          <div className="w-rows">
            {list.map(([sec, rule, app]) => (
              <div key={sec} className="w-rule">
                <span className="w-sec">§{sec}</span>
                <span>
                  <span style={{ display: 'block' }}>{rule}</span>
                  {app && <span className="t12 sub" style={{ display: 'block', marginTop: 4 }}>في نماء: {app}</span>}
                </span>
              </div>
            ))}
          </div>
        </section>
      ))}
      <p className="w-note" style={{ marginTop: 18 }}><Icon as={Info} size={14} />
        <span>الدليل إرشادي، مبني على {ZATCA.basis}، ولا يُعد مستندًا نظاميًا ولا ملزمًا للهيئة. وزكاة المواشي والمحاصيل من {ZATCA.guides.livestockCrops.title}. الحساب في نماء استرشادي، وفي المسائل الخاصة ارجع لأهل العلم.</span>
      </p>
    </Card>
  );
}

